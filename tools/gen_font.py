#!/usr/bin/env python3
"""Rasterize a TTF into 4-bit-alpha monospace bitmap fonts for bp-ui.

Usage: python3 tools/gen_font.py <font-dir> <out.rs>
Generated output is committed; the device never parses TTF at runtime.
Font: JetBrains Mono (SIL OFL 1.1), see crates/bp-ui/fonts/.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

FONT_DIR = sys.argv[1]
OUT = sys.argv[2]
# (rust name, file, pixel size)
SPECS = [
    ("SMALL", "JetBrainsMono-Regular.ttf", 15),
    ("BODY", "JetBrainsMono-Medium.ttf", 20),
    ("TITLE", "JetBrainsMono-Bold.ttf", 28),
    ("HUGE", "JetBrainsMono-ExtraBold.ttf", 56),
]
FIRST, LAST = 0x20, 0x7E

out = ["// @generated by tools/gen_font.py from JetBrains Mono (SIL OFL 1.1). Do not edit.",
       "use super::Font;", ""]
for name, fname, px in SPECS:
    f = ImageFont.truetype(f"{FONT_DIR}/{fname}", px)
    ascent, descent = f.getmetrics()
    adv = round(f.getlength("M"))
    h = ascent + descent
    data = bytearray()
    for cp in range(FIRST, LAST + 1):
        img = Image.new("L", (adv, h), 0)
        ImageDraw.Draw(img).text((0, 0), chr(cp), font=f, fill=255)
        px_vals = img.tobytes()
        # pack 4bpp, high nibble first
        nib = [min(15, (v + 8) // 17) for v in px_vals]
        if len(nib) % 2:
            nib.append(0)
        for i in range(0, len(nib), 2):
            data.append((nib[i] << 4) | nib[i + 1])
    stride = (adv * h + 1) // 2
    out.append(f"static {name}_DATA: [u8; {len(data)}] = [")
    for i in range(0, len(data), 32):
        out.append("    " + ", ".join(str(b) for b in data[i:i + 32]) + ",")
    out.append("];")
    out.append(f"pub static {name}: Font = Font {{ width: {adv}, height: {h}, baseline: {ascent}, "
               f"first: {FIRST}, last: {LAST}, glyph_stride: {stride}, data: &{name}_DATA }};")
    out.append("")
open(OUT, "w").write("\n".join(out))
print("wrote", OUT)
