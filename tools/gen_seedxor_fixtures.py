#!/usr/bin/env python3
"""Fixtures for bp-backup's Seed XOR test: Coldcard's deterministic parts,
computed with Python's hashlib (independent of our SHA-256).

usage: python3 -I tools/gen_seedxor_fixtures.py > crates/bp-backup/tests/data/seedxor_split.txt
"""
import hashlib


def sha256d(b):
    return hashlib.sha256(hashlib.sha256(b).digest()).digest()


def split(secret, n):
    parts = []
    for i in range(n - 1):
        parts.append(sha256d(b"Batshitoshi " + secret + b"%d of %d parts" % (i, n))[: len(secret)])
    last = bytearray(secret)
    for p in parts:
        last = bytearray(a ^ b for a, b in zip(last, p))
    parts.append(bytes(last))
    return parts


print("# Coldcard Seed XOR deterministic parts (shared/xor_seed.py formula),")
print("# from Python hashlib. Generated by tools/gen_seedxor_fixtures.py.")
print("# secret n part0 part1 ...")
for length in (16, 20, 24, 28, 32):
    for n in (2, 3, 4):
        secret = hashlib.sha256(b"seed xor fixture %d %d" % (length, n)).digest()[:length]
        print(secret.hex(), n, " ".join(p.hex() for p in split(secret, n)))
