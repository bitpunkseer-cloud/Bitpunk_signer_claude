#!/usr/bin/env python3
"""Rasterize the non-ASCII glyphs the UI uses (Korean) into 2-bit wide glyphs.

Usage: python3 tools/gen_hangul.py [font-dir]

Collects every non-ASCII character of the string literals in
crates/bp-app/src/text.rs, renders them with Noto Sans KR (SIL OFL 1.1) at
the SMALL, BODY and TITLE sizes into cells two ASCII columns wide, and writes
crates/bp-ui/src/font/hangul.rs. Only the characters the UI uses are stored
(Keystone's approach), with 2-bit coverage to save flash.

The font files are not stored in this repository: they are downloaded from a
pinned notofonts/noto-cjk commit into <font-dir> (default: target/fonts) and
checked against their SHA-256 before use.
"""
import hashlib
import os
import re
import sys
import urllib.request

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
TEXT_RS = os.path.join(ROOT, "crates/bp-app/src/text.rs")
OUT = os.path.join(ROOT, "crates/bp-ui/src/font/hangul.rs")
FONT_DIR = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "target/fonts")

COMMIT = "f8d157532fbfaeda587e826d4cd5b21a49186f7c"
FONTS = {
    "Regular": "69975a0ac8472717870aefeab0a4d52739308d90856b9955313b2ad5e0148d68",
    "Medium": "b46988ef13e8bac08f3933af686eaf770972994f9b6d335be0184d60169b5431",
    "Bold": "5a6ceb287ed2fc6cfc6213144ebea68cbd94b20fc9eb873d8486493bf02d9bda",
}
# (rust name, Noto weight, pixel size); each glyph fits a cell two ASCII
# columns wide and one line high, on the ASCII baseline (metrics read from
# data.rs, JetBrains Mono)
SPECS = [
    ("SMALL", "Regular", 15),
    ("BODY", "Medium", 20),
    ("TITLE", "Bold", 28),
]


def ascii_metrics():
    data = open(os.path.join(ROOT, "crates/bp-ui/src/font/data.rs")).read()
    out = {}
    for m in re.finditer(r"pub static (\w+): Font = Font \{\s*width: (\d+),\s*height: (\d+),\s*baseline: (\d+),", data):
        out[m.group(1)] = (int(m.group(2)), int(m.group(3)), int(m.group(4)))
    return out


def font_path(weight):
    os.makedirs(FONT_DIR, exist_ok=True)
    path = os.path.join(FONT_DIR, f"NotoSansKR-{weight}.otf")
    if not os.path.exists(path):
        url = f"https://raw.githubusercontent.com/notofonts/noto-cjk/{COMMIT}/Sans/SubsetOTF/KR/NotoSansKR-{weight}.otf"
        print("downloading", url)
        urllib.request.urlretrieve(url, path)
    digest = hashlib.sha256(open(path, "rb").read()).hexdigest()
    if digest != FONTS[weight]:
        sys.exit(f"{path}: SHA-256 {digest} does not match the pinned font")
    return path


def literals(src):
    """String literal contents, skipping // comments, char literals and
    lifetimes (same rules as the glyph coverage test in text.rs)."""
    out, i, n = [], 0, len(src)
    while i < n:
        c = src[i]
        if src.startswith("//", i):
            i = src.find("\n", i)
            i = n if i < 0 else i
        elif c == '"':
            i += 1
            lit = []
            while i < n and src[i] != '"':
                if src[i] == "\\":
                    lit.append(src[i:i + 2])
                    i += 2
                else:
                    lit.append(src[i])
                    i += 1
            out.append("".join(lit))
            i += 1
        elif c == "'":
            if src.startswith("\\", i + 1):
                i = src.index("'", i + 3) + 1
            elif i + 2 < n and src[i + 2] == "'":
                i += 3
            else:
                i += 1  # a lifetime
        else:
            i += 1
    return out


def used_chars():
    src = open(TEXT_RS, encoding="utf-8").read()
    return sorted({ch for lit in literals(src) for ch in lit if not ch.isascii()})


def main():
    metrics = ascii_metrics()
    chars = used_chars()
    out = [
        "// @generated by tools/gen_hangul.py from Noto Sans KR (SIL OFL 1.1). Do not edit.",
        f"// {len(chars)} glyphs: every non-ASCII character used in crates/bp-app/src/text.rs.",
        "use super::Wide;",
        "",
        "pub static CHARS: [u32; %d] = [%s];" % (len(chars), ", ".join(str(ord(c)) for c in chars)),
        "",
    ]
    total = 0
    for name, weight, px in SPECS:
        adv, h, ascent = metrics[name]
        cell = 2 * adv
        f = ImageFont.truetype(font_path(weight), px)
        k_ascent, _ = f.getmetrics()
        bits = []
        for ch in chars:
            img = Image.new("L", (cell, h), 0)
            w = f.getlength(ch)
            ImageDraw.Draw(img).text(((cell - w) / 2, ascent - k_ascent), ch, font=f, fill=255)
            bits.extend(min(3, (v + 42) // 85) for v in img.tobytes())
        stride_px = cell * h
        stride = (stride_px * 2 + 7) // 8
        data = bytearray()
        for g in range(len(chars)):
            px_vals = bits[g * stride_px:(g + 1) * stride_px]
            px_vals += [0] * (stride * 4 - len(px_vals))
            for i in range(0, len(px_vals), 4):
                a, b, c, d = px_vals[i:i + 4]
                data.append((a << 6) | (b << 4) | (c << 2) | d)
        total += len(data)
        out.append(f"static {name}_DATA: [u8; {len(data)}] = [")
        for i in range(0, len(data), 32):
            out.append("    " + ", ".join(str(b) for b in data[i:i + 32]) + ",")
        out.append("];")
        out.append(
            f"pub static {name}: Wide = Wide {{ width: {cell}, height: {h}, glyph_stride: {stride}, "
            f"chars: &CHARS, data: &{name}_DATA }};"
        )
        out.append("")
    open(OUT, "w", encoding="utf-8").write("\n".join(out))
    print(f"wrote {OUT}: {len(chars)} glyphs, {total} bytes")


if __name__ == "__main__":
    main()
