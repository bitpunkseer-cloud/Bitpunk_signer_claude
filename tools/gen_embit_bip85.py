#!/usr/bin/env python3
"""Generate BIP-85 test vectors with embit, as an outside oracle.

    python3 -I tools/gen_embit_bip85.py <path to embit/src>

embit is the library behind SeedSigner, Krux and Specter DIY. Bitpunk does
not use or copy its code: this script records what embit derives for the
"abandon ... about" seed at indexes and lengths the specification's vectors
do not cover. Writes crates/bp-bitcoin/tests/data/embit_bip85.rs.
"""

import os
import sys

if len(sys.argv) != 2:
    sys.exit(__doc__)
sys.path.insert(0, os.path.abspath(sys.argv[1]))

from embit import bip32, bip39, bip85  # noqa: E402

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "crates/bp-bitcoin/tests/data/embit_bip85.rs")

seed = bip39.mnemonic_to_seed("abandon " * 11 + "about")
root = bip32.HDKey.from_seed(seed)
rows = []
for words in (12, 18, 24):
    for index in (0, 1, 7, 2147483647):
        rows.append(("Bip39 { words: %d }" % words, index, bip85.derive_mnemonic(root, words, index)))
for index in (0, 3, 1000):
    rows.append(("Wif", index, bip85.derive_wif(root, index).wif()))
    rows.append(("Xprv", index, bip85.derive_xprv(root, index).to_base58()))
for nbytes in (16, 32, 64):
    for index in (0, 2):
        rows.append(("Hex { bytes: %d }" % nbytes, index, bip85.derive_hex(root, nbytes, index).hex()))

with open(OUT, "w") as f:
    f.write("// Generated by tools/gen_embit_bip85.py (embit as an outside oracle).\n")
    f.write("// Root: BIP-39 \"abandon ... about\", no passphrase. Do not edit.\n\n")
    f.write("pub const VECTORS: &[(App, u32, &str)] = &[\n")
    for app, index, out in rows:
        f.write("    (App::%s, %d, \"%s\"),\n" % (app, index, out))
    f.write("];\n")
print("wrote", OUT, len(rows), "vectors")
