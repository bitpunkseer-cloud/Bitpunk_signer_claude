#!/usr/bin/env python3
"""Fixtures for bp-backup's SLIP-39 tests, from the reference implementation.

usage: python3 -I tools/gen_slip39_fixtures.py <dir holding shamir_mnemonic> <vectors.json> <out dir>

Writes slip39_vectors.txt (the published vectors, as text) and
slip39_split.txt (sets made by the reference with a fixed random stream:
SHA-256(seed || counter) blocks, which the Rust test replays).
"""
import hashlib, json, os, sys

sys.path.insert(0, sys.argv[1])
import shamir_mnemonic.shamir as shamir  # noqa: E402

out = sys.argv[3]

with open(sys.argv[2]) as f:
    vectors = json.load(f)
with open(os.path.join(out, "slip39_vectors.txt"), "w") as f:
    f.write("# SLIP-39 test vectors (passphrase TREZOR), from\n")
    f.write("# https://github.com/trezor/python-shamir-mnemonic vectors.json (MIT).\n")
    f.write("# Generated by tools/gen_slip39_fixtures.py; do not edit by hand.\n")
    for desc, mnemonics, ms, xprv in vectors:
        f.write("\n## %s\n" % desc)
        for m in mnemonics:
            f.write("share %s\n" % m)
        f.write("secret %s\n" % (ms or "-"))
        f.write("xprv %s\n" % (xprv or "-"))


class Stream:
    def __init__(self, seed):
        self.seed, self.counter, self.buf = seed, 0, b""

    def __call__(self, n):
        while len(self.buf) < n:
            self.buf += hashlib.sha256(self.seed + self.counter.to_bytes(4, "big")).digest()
            self.counter += 1
        r, self.buf = self.buf[:n], self.buf[n:]
        return r


CONFIGS = [
    (1, [(1, 1)]),
    (1, [(2, 3)]),
    (1, [(3, 5)]),
    (1, [(16, 16)]),
    (2, [(1, 1), (2, 3), (3, 5)]),
    (2, [(2, 2), (2, 3)]),
    (3, [(1, 1), (1, 1), (2, 3), (2, 3)]),
    (1, [(1, 1), (5, 7)]),
    (4, [(1, 1), (2, 2), (2, 3), (3, 4), (2, 5)]),
    (16, [(1, 1)] * 16),
]
with open(os.path.join(out, "slip39_split.txt"), "w") as f:
    f.write("# SLIP-39 sets made by python-shamir-mnemonic 0.3.0 (MIT) with a fixed\n")
    f.write("# random stream SHA-256(seed || counter_be32). Generated by\n")
    f.write("# tools/gen_slip39_fixtures.py; do not edit by hand.\n")
    case = 0
    for length in (16, 32, 18, 24):
        for ci, (gt, groups) in enumerate(CONFIGS):
            for ext in (True, False):
                if length in (18, 24) and ci % 3:
                    continue
                case += 1
                seed = hashlib.sha256(b"bitpunk slip39 fixture %d" % case).digest()
                secret = hashlib.sha256(b"secret %d" % case).digest()[:length]
                passphrase = [b"", b"TREZOR", b"a b ~ !", b"x" * 40][case % 4]
                exp = case % 2
                shamir.RANDOM_BYTES = Stream(seed)
                sets = shamir.generate_mnemonics(gt, groups, secret, passphrase, ext, exp)
                f.write("\n## case %d\n" % case)
                f.write("seed %s\n" % seed.hex())
                f.write("secret %s\n" % secret.hex())
                f.write("passphrase %s\n" % (passphrase.hex() or "-"))
                f.write("ext %d exp %d\n" % (ext, exp))
                f.write("groups %d %s\n" % (gt, " ".join("%d/%d" % g for g in groups)))
                for group in sets:
                    for m in group:
                        f.write("share %s\n" % m)
print("ok", case)
