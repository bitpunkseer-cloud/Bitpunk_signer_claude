#!/usr/bin/env python3
"""Generate the BIP-39 English wordlist as Rust source.

Usage: python3 tools/gen_wordlist.py english.txt crates/bp-bitcoin/src/bip39/wordlist_en.rs
Source: https://github.com/bitcoin/bips/blob/master/bip-0039/english.txt
The SHA-256 of the source file is pinned below and re-checked by tests.
"""
import hashlib, sys
src, out = sys.argv[1], sys.argv[2]
raw = open(src, "rb").read()
digest = hashlib.sha256(raw).hexdigest()
assert digest == "2f5eed53a4727b4bf8880d8f3f199efc90e58503646d9ff8eff3a2ed3b24dbda", digest
words = raw.decode().split("\n")[:-1]
assert len(words) == 2048 and words == sorted(words)
lines = ["// @generated by tools/gen_wordlist.py from bitcoin/bips bip-0039/english.txt",
         f"// source SHA-256: {digest}", "",
         "pub static WORDS: [&str; 2048] = ["]
for i in range(0, 2048, 8):
    lines.append("    " + " ".join(f'"{w}",' for w in words[i:i+8]))
lines.append("];")
open(out, "w").write("\n".join(lines) + "\n")
print("wrote", out)
