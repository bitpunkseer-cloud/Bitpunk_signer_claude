#!/usr/bin/env python3
"""Generate multisig test vectors with embit, as an outside oracle.

    python3 -I tools/gen_embit_vectors.py <path to embit/src>

embit is the library behind SeedSigner, Krux and Specter DIY. Bitpunk does
not use or copy its code: this script only records what embit computes
(descriptor checksums, BIP-67 scripts, addresses) for fixed keys, so the
Rust tests can require that Bitpunk agrees with it, as well as with
rust-miniscript and the BIP vectors. Writes
crates/bp-bitcoin/tests/data/embit_multisig.rs.
"""

import os
import sys

if len(sys.argv) != 2:
    sys.exit(__doc__)
sys.path.insert(0, os.path.abspath(sys.argv[1]))

from embit import bip32  # noqa: E402
from embit.descriptor import Descriptor  # noqa: E402
from embit.descriptor.checksum import checksum  # noqa: E402
from embit.networks import NETWORKS  # noqa: E402

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "crates/bp-bitcoin/tests/data/embit_multisig.rs")

# (wrapper, m, n, network, account)
CASES = [
    ("wsh", 2, 3, "main", 0),
    ("sh-wsh", 2, 3, "main", 0),
    ("wsh", 3, 5, "test", 0),
    ("wsh", 1, 1, "main", 0),
    ("wsh", 2, 3, "main", 7),
    ("sh-wsh", 4, 7, "test", 1),
    ("wsh", 7, 15, "main", 0),
    ("sh-wsh", 15, 15, "test", 0),
]
INDEXES = [0, 1, 2, 19, 1000, 2**31 - 1]


def key(seed_byte, wrapper, net, account):
    root = bip32.HDKey.from_seed(bytes([seed_byte] * 32), version=NETWORKS[net]["xprv"])
    coin = 0 if net == "main" else 1
    t = 2 if wrapper == "wsh" else 1
    path = "m/48h/%dh/%dh/%dh" % (coin, account, t)
    x = root.derive(path).to_public()
    return "[%s%s]%s/<0;1>/*" % (root.my_fingerprint.hex(), path[1:], x.to_base58(NETWORKS[net]["xpub"]))


def main():
    lines = [
        "// Generated by tools/gen_embit_vectors.py with embit (an outside oracle; not",
        "// used by Bitpunk). Do not edit. (descriptor with checksum, network, receive",
        "// addresses, change addresses) at the listed indexes.",
        "pub const INDEXES: [u32; %d] = %s;" % (len(INDEXES), "[" + ", ".join(str(i) for i in INDEXES) + "]"),
        "pub const VECTORS: &[(&str, &str, &[&str], &[&str])] = &[",
    ]
    for wrapper, m, n, net, account in CASES:
        keys = [key(10 + i, wrapper, net, account) for i in range(n)]
        inner = "sortedmulti(%d,%s)" % (m, ",".join(keys))
        body = "wsh(%s)" % inner if wrapper == "wsh" else "sh(wsh(%s))" % inner
        d = Descriptor.from_string(body)
        cs = checksum(body)
        addrs = []
        for branch in (0, 1):
            addrs.append([d.derive(i, branch_index=branch).address(NETWORKS[net]) for i in INDEXES])
        lines.append("    (")
        lines.append('        "%s#%s",' % (body, cs))
        lines.append('        "%s",' % net)
        for a in addrs:
            lines.append("        &[%s]," % ", ".join('"%s"' % x for x in a))
        lines.append("    ),")
    lines.append("];")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", OUT, len(CASES), "wallets")


main()
