//! Backup and tool strings (M11). SLIP-39 first (M11-2).

/// Why a share was refused, in `slip39ui::error_index` order.
pub const SL_ERRORS: usize = 7;

pub struct BackupStrings {
    // menus and About
    pub sl_new_menu: &'static str,
    pub sl_load_menu: &'static str,
    pub sl_opt_shares: &'static str,
    pub miniscript: &'static str,
    // typing shares
    pub sl_title: &'static str,
    pub sl_length_q: &'static str,
    pub sl_lengths: [&'static str; 2],
    pub sl_length_note: &'static str,
    /// "Share {}: word {} of {}"
    pub sl_share_word: &'static str,
    /// "Share {}: type word {} again"
    pub sl_fix_word: &'static str,
    pub sl_checksum: [&'static str; 2],
    /// Accepted, typed before, not needed.
    pub sl_added: [&'static str; 3],
    /// Other set, member threshold, same number, digest, group threshold,
    /// padding, not a share.
    pub sl_errors: [&'static str; SL_ERRORS],
    /// "Set {}: {} of {} groups needed" (first two words)
    pub sl_set: &'static str,
    /// "Group {}: {} of {} shares"
    pub sl_group: &'static str,
    /// "Shares still needed: {}" (one group)
    pub sl_more_shares: &'static str,
    /// "Groups still needed: {}"
    pub sl_more_groups: &'static str,
    pub sl_enough: &'static str,
    pub sl_next: &'static str,
    pub sl_open: &'static str,
    pub sl_pass_title: &'static str,
    pub sl_pass_notes: [&'static str; 2],
    pub sl_slow: &'static str,
    pub sl_working: &'static str,
    pub sl_ready_title: &'static str,
    /// "{} words, {} of {} groups"
    pub sl_ready_info: &'static str,
    pub sl_load: &'static str,
    // making shares
    pub sl_source_q: &'static str,
    pub sl_strength_q: &'static str,
    pub sl_groups_q: &'static str,
    pub sl_presets: [&'static str; 4],
    pub sl_preset_notes: [&'static str; 4],
    pub sl_needed: &'static str,
    /// "Group {} needs"
    pub sl_g_needs: &'static str,
    /// "Group {} shares"
    pub sl_g_shares: &'static str,
    pub sl_n_groups: &'static str,
    pub sl_make: &'static str,
    pub sl_rule: &'static str,
    /// "{} shares in all"
    pub sl_total: &'static str,
    pub sl_mix_q: &'static str,
    pub sl_mix: [&'static str; 2],
    pub sl_mix_notes: [&'static str; 2],
    pub sl_dice_title: &'static str,
    /// "{} rolls (50 or more)"
    pub sl_dice_count: &'static str,
    pub sl_dice_short: &'static str,
    /// "Group {}, share {} of {}"
    pub sl_show_title: &'static str,
    pub sl_show_note: &'static str,
    pub sl_covered: &'static str,
    /// "Share {} of {}: which is word {}?"
    pub sl_check_q: &'static str,
    pub sl_check_wrong: &'static str,
    pub sl_done: &'static str,
    pub h_next_share: &'static str,
    pub h_check: &'static str,
}

