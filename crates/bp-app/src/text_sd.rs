//! microSD strings (M8).

/// Card problems, in `sd::CardProblem` order.
pub const CARD_PROBLEMS: usize = 7;
/// File kinds, in `sd::FileKind` order.
pub const FILE_KINDS: usize = 6;

pub struct SdStrings {
    pub menu: &'static str,
    pub badge: &'static str,
    pub reading: &'static str,
    pub fs: &'static str,
    pub size: &'static str,
    pub cluster: &'static str,
    pub entries: &'static str,
    pub refresh: &'static str,
    pub power_note: &'static str,
    pub removed: &'static str,
    /// Title and two explanation lines per problem.
    pub problems: [[&'static str; 3]; CARD_PROBLEMS],
    pub browse: &'static str,
    pub format: &'static str,
    pub empty_dir: &'static str,
    /// "{} hidden"
    pub hidden: &'static str,
    /// "{}-{} of {}"
    pub range: &'static str,
    pub too_deep: &'static str,
    pub not_ready: &'static str,
    pub name: &'static str,
    pub size_label: &'static str,
    pub kind_label: &'static str,
    pub kinds: [&'static str; FILE_KINDS],
    pub view_text: &'static str,
    pub delete: &'static str,
    pub truncated: &'static str,
    pub delete_q: &'static str,
    pub delete_note: &'static str,
    pub deleted: &'static str,
    pub delete_failed: &'static str,
    pub cancel: &'static str,
    pub proceed: &'static str,
    pub format_warn: [&'static str; 3],
    pub format_final: [&'static str; 2],
    pub format_go: &'static str,
    pub formatted: &'static str,
    pub format_failed: &'static str,
    pub h_scroll: &'static str,
    pub wipe_setting: &'static str,
    pub sign_psbt: &'static str,
    pub psbt_none: [&'static str; 2],
    pub sign: &'static str,
    pub sign_message: &'static str,
    pub too_large: &'static str,
    pub bad_encoding: &'static str,
    pub msg_too_large: &'static str,
    pub save_sd: &'static str,
    pub done: &'static str,
    pub saving: &'static str,
    pub saved: &'static str,
    /// "File: {}"
    pub saved_as: &'static str,
    pub wiped_original: &'static str,
    pub remove_ok: &'static str,
    pub save_failed: &'static str,
    /// No card, write failed, card full, folder full, card refused.
    pub save_problems: [&'static str; 5],
    pub retry: &'static str,
    /// "Cluster {} - Root entries {}"
    pub detail_line: &'static str,
    /// M9-8 directory listing: "Volume FAT16  16.6 MB", totals line
    pub volume: &'static str,
    /// "{files} {bytes} {folders}"
    pub totals: &'static str,
    /// Under the file type: how it was decided
    pub kind_note: &'static str,
    /// Signed screen of a PSBT file.
    pub signed_sd: &'static str,
    pub import_wallet: &'static str,
    pub import_settings: &'static str,
    /// QR screen key help: S saves the shown export as a file.
    pub qr_save: &'static str,
    /// Export menu row: label and detail.
    pub bpw_export: (&'static str, &'static str),
    pub file_too_large: &'static str,
    pub registered_from_file: &'static str,
}

