//! microSD strings (M8).

/// Card problems, in `sd::CardProblem` order.
pub const CARD_PROBLEMS: usize = 7;
/// File kinds, in `sd::FileKind` order.
pub const FILE_KINDS: usize = 6;

pub struct SdStrings {
    pub menu: &'static str,
    pub badge: &'static str,
    pub reading: &'static str,
    pub fs: &'static str,
    pub size: &'static str,
    pub cluster: &'static str,
    pub entries: &'static str,
    pub refresh: &'static str,
    pub power_note: &'static str,
    pub removed: &'static str,
    /// Title and two explanation lines per problem.
    pub problems: [[&'static str; 3]; CARD_PROBLEMS],
    pub browse: &'static str,
    pub format: &'static str,
    pub empty_dir: &'static str,
    /// "{} hidden"
    pub hidden: &'static str,
    /// "{}-{} of {}"
    pub range: &'static str,
    pub too_deep: &'static str,
    pub not_ready: &'static str,
    pub name: &'static str,
    pub size_label: &'static str,
    pub kind_label: &'static str,
    pub kinds: [&'static str; FILE_KINDS],
    pub view_text: &'static str,
    pub delete: &'static str,
    pub truncated: &'static str,
    pub delete_q: &'static str,
    pub delete_note: &'static str,
    pub deleted: &'static str,
    pub delete_failed: &'static str,
    pub cancel: &'static str,
    pub proceed: &'static str,
    pub format_warn: [&'static str; 3],
    pub format_final: [&'static str; 2],
    pub format_go: &'static str,
    pub formatted: &'static str,
    pub format_failed: &'static str,
    pub h_scroll: &'static str,
}

