//! Vault and PIN strings (M10-4).

/// Vault problems, in `vaultui::problem_index` order (error codes E-VLT-nn).
pub const VAULT_PROBLEMS: usize = 3;

pub struct VaultStrings {
    // lock screen
    pub locked_title: &'static str,
    pub path: &'static str,
    pub prefix_label: &'static str,
    pub prefix_note: &'static str,
    pub suffix_label: &'static str,
    pub words_title: &'static str,
    pub words_same: &'static str,
    pub words_different: &'static str,
    pub working: &'static str,
    pub working_lines: [&'static str; 2],
    /// "Wrong PIN. {} attempts left."
    pub wrong: &'static str,
    /// "{} wrong PINs: wait {}" (count, m:ss)
    pub delay: &'static str,
    pub delay_note: &'static str,
    pub wiped_title: &'static str,
    pub wiped_lines: [&'static str; 2],
    /// Corrupt, rollback, hardware.
    pub problems: [&'static str; VAULT_PROBLEMS],
    pub problem_next: &'static str,
    pub without: &'static str,
    pub h_unlock: &'static str,
    pub h_without: &'static str,
    pub h_retype: &'static str,
    // setting or changing the PIN
    pub setup_title: &'static str,
    pub change_title: &'static str,
    pub rules: [&'static str; 4],
    pub new_prefix: &'static str,
    pub new_suffix: &'static str,
    pub again_prefix: &'static str,
    pub again_suffix: &'static str,
    pub too_short: &'static str,
    pub mismatch: &'static str,
    pub remember_title: &'static str,
    pub remember_lines: [&'static str; 3],
    pub unlock_first: &'static str,
    // security menu
    pub menu: &'static str,
    pub row_pin: &'static str,
    pub row_lock: &'static str,
    pub row_wipe: &'static str,
    pub wipe_title: &'static str,
    pub wipe_lines: [&'static str; 2],
    pub wiped_done: &'static str,
    pub no_vault: &'static str,
    pub no_hw: &'static str,
    pub save_failed: &'static str,
    pub wallet_full: &'static str,
    // the seed vault (M10-5)
    pub sv_menu: &'static str,
    pub sv_no_vault: &'static str,
    /// "{} of {} seeds in the vault"
    pub sv_count: &'static str,
    pub sv_never: &'static str,
    pub sv_store: &'static str,
    pub sv_loaded: &'static str,
    pub sv_load: &'static str,
    pub sv_remove: &'static str,
    pub sv_pick: &'static str,
    pub sv_put: &'static str,
    pub sv_nothing: &'static str,
    pub sv_full: &'static str,
    pub sv_stored: &'static str,
    pub sv_stored_pass: &'static str,
    pub sv_already: &'static str,
    pub sv_bad: &'static str,
    pub sv_remove_title: &'static str,
    pub sv_remove_line: &'static str,
    pub sv_removed: &'static str,
}

